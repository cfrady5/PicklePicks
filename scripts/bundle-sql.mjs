// Concatenates supabase/migrations/*.sql into supabase/setup.sql so a fresh
// project can be set up with one paste into the Supabase SQL editor.
import fs from "node:fs";
import path from "node:path";
const dir = path.join(process.cwd(), "supabase", "migrations");
const files = fs.readdirSync(dir).filter((f) => f.endsWith(".sql")).sort();
const header = `-- GENERATED by scripts/bundle-sql.mjs — do not edit by hand.\n-- Source: ${files.join(", ")}\n-- Run once on a fresh Supabase project (SQL editor → New query → paste → Run).\n\nbegin;\n\n`;
const body = files.map((f) => `-- ================= ${f} =================\n${fs.readFileSync(path.join(dir, f), "utf8").trim()}\n`).join("\n");
fs.writeFileSync(path.join(process.cwd(), "supabase", "setup.sql"), `${header}${body}\ncommit;\n`);
console.log(`wrote supabase/setup.sql from ${files.length} migrations`);
